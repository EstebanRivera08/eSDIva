"""Write the agent-facing API map `skills/esdiva-simulate/references/api-map.md`.

The map lets an agent answer most eSDIva questions without reading the source:
every public signature with its one-line summary and `file:line`, under a short
hand-written guide to which module owns what. Signatures are pulled from the live
package, so the map cannot drift silently — `tests/integration/test_api_map.py`
fails when it is stale. Regenerate with `just api-map`.
"""

import inspect
import sys
from pathlib import Path

import esdiva
from esdiva import beamforming, io, plotting, reception, transducers, utilities

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "skills" / "esdiva-simulate" / "references" / "api-map.md"

HEADER = """\
# eSDIva API map

<!-- GENERATED by scripts/gen_api_map.py — edit HEADER there, then `just api-map`. -->

Read this before opening any source file. It holds every public signature, its
one-line purpose and its `file:line`, so most questions need no source read at
all. Open source only for behaviour a signature can't show, and then jump straight
to the line given here. Units: public API in mm (`_mm`), internals SI.

## Where things live

| Module | Owns | Open it when |
|---|---|---|
| `emission/emission.py` | `Emission`: pressure field p(r,t) or \\|P(r,fc)\\| on a grid; method routing, excitation/IR, attenuation, soft baffle | field shape, units, time grid, method choice |
| `reception/base.py` | `ReceptionBase`: shared `sequence_rf`, `synthetic_aperture_rf`, `scan_focusline`, `show`, `t0` finalisation (lens sag), checkpointing | sequences, FMC, moving scatterers, `t0` |
| `reception/reception.py` | `Reception`: fast pulse-echo kernel, `pulse_echo_rf`, `method=None` temporal/spectral routing | single-shot RF, PSF, method choice |
| `reception/conventional.py` | `ReceptionConventional`: sampled-SIR FFT-convolution backend | temporal/fst/auto path internals |
| `hsir/sir_temporal.py` | sampled SIR h(t) (SDI/FST numba kernels), `place_twoway_rf` | SIR accuracy, float32 cumsum, echo placement |
| `hsir/sir_spectral.py` | closed-form SIR spectrum H(ω) per patch, fused two-way spectrum | spectral path, attenuation in reception |
| `hsir/sir_paired.py` | pedagogic two-way delta train (`ReceptionPaired`) | only for the paired method |
| `attenuation/attenuation.py` | causal power-law H_att(f), path distances | attenuation / dispersion |
| `transducers/base.py` | `TransducerBase`: lazy geometry, delays, apodization, IR, `transform`, `copy`, mesh | anything every probe shares |
| `transducers/{linear,matrix,circular,radial,custom,fieldii_compat}.py` | concrete probes and their geometry/apodization | one probe type's geometry |
| `transducers/saved_transducers.py` | `Domino` (128-el linear), `Zeus_Matrix` (55×55) | ready-made probes |
| `fields.py` | `Field`: move (4×4 mm), resample, add fields | posing/compounding volumes |
| `plotting/plotting2D.py` | Matplotlib slices, planes, transient animations | 2-D figures |
| `plotting/plotting3D.py` | one-call PyVista volume/slice figures | quick 3-D figure |
| `plotting/plotting_pyvista.py` + `pyvista_functions.py` | `add_*` scene builders (take `plotter=`, never `show()`), `create_*_mesh` | composing 3-D scenes |
| `plotting/export_utils.py` | screenshots, PyVista/Matplotlib movies | saving figures |
| `beamforming/das.py` | DAS scanline, general 3-D DAS (`das_volume`), RCA DAS, envelope | imaging from RF |
| `io/rf_dataset.py`, `io/hdf5.py` | checkpointed RF store, HDF5/USTB export | long runs, interchange |
| `utilities/` | phantoms, noise, grids, dB, time alignment, runtime estimate, brain atlas | helpers |

Deeper, by topic: `transducers.md`, `emission.md`, `reception.md`,
`visualization.md`, `physics.md`, `validation.md` (same folder). Physics ground
truth for maintainers: `.claude/rules/physics-context.md`. With a
`graphify-out/` folder, `graphify query "<question>"` scopes a source dive.
"""

# (section title, namespace, names). Classes also list their own public methods.
SECTIONS = [
    ("Emission", esdiva, ["Emission"]),
    ("Reception", reception, ["Reception", "ReceptionConventional"]),
    ("Reception — shared methods (`ReceptionBase`)", reception.base, ["ReceptionBase"]),
    ("Transducers", transducers, transducers.__all__),
    ("Moving / compounding fields", esdiva, ["Field"]),
    ("Plotting", plotting, [n for n in plotting.__all__ if n[0].islower()]),
    ("Beamforming", beamforming, beamforming.__all__),
    ("RF storage and export", io, io.__all__),
    ("Utilities", utilities, [n for n in utilities.__all__ if n != "BG_Atlas"]),
]


def _summary(obj) -> str:
    doc = inspect.getdoc(obj) or ""
    return doc.strip().split("\n\n")[0].replace("\n", " ")


def _where(obj) -> str:
    obj = inspect.unwrap(getattr(obj, "fget", obj))
    try:
        path = Path(inspect.getsourcefile(obj)).resolve().relative_to(ROOT)
        return f"{path.as_posix()}:{inspect.getsourcelines(obj)[1]}"
    except (TypeError, OSError):
        return "?"


def _sig(name, obj) -> str:
    try:
        sig = (
            str(inspect.signature(obj)).replace("(self, ", "(").replace("(self)", "()")
        )
    except (TypeError, ValueError):
        sig = ""
    return f"`{name}{sig}`"


def _entry(name, obj, indent="") -> list[str]:
    summary = f" — {_summary(obj)}" if obj.__doc__ else ""
    return [f"{indent}- {_sig(name, obj)}{summary} `{_where(obj)}`"]


def _class(name, cls) -> list[str]:
    lines = [f"### `{name}`", "", f"{_summary(cls)} `{_where(cls)}`", ""]
    if "__init__" in vars(cls):  # Constructor: signature only, its doc is the class's.
        lines.append(f"- {_sig(name, cls.__init__)} `{_where(cls.__init__)}`")
    for attr, member in vars(cls).items():
        if attr.startswith("_") and not (attr == "__call__" and member.__doc__):
            continue
        if isinstance(member, property):
            lines.append(f"  - `.{attr}` (property) — {_summary(member)}")
        elif inspect.isfunction(member) or isinstance(member, staticmethod):
            lines += _entry(f".{attr}", getattr(cls, attr), indent="  ")
    return [*lines, ""]


def render() -> str:
    out = [HEADER]
    for title, ns, names in SECTIONS:
        out += [f"## {title}", ""]
        for name in names:
            obj = getattr(ns, name)
            out += _class(name, obj) if inspect.isclass(obj) else _entry(name, obj)
        out.append("")
    return "\n".join(out).rstrip() + "\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(render())} chars)", file=sys.stderr)
